    getIconHTML(iconId, customSvg = "", type = "hotspot") {
        if (iconId === "custom") {
            if (customSvg && customSvg.trim()) {
                const trimmed = customSvg.trim();
                if (trimmed.startsWith("<svg") || trimmed.startsWith("<?xml")) {
                    return trimmed;
                }
                const symbols = Array.from(trimmed).slice(0, 3).join("");
                const fontClass = symbols.length > 2 ? "lo-icon-glyph lo-icon-compact" : "lo-icon-glyph";
                return `<span class="${fontClass}">${symbols}</span>`;
            }
            return type === "portal" ? "🌀" : "";
        }

        const defaultId = type === "portal" ? "portal" : "default";
        const targetId = iconId || defaultId;
        const preset = this.presets[targetId];

        if (!preset) {
            return type === "portal" ? "🌀" : "";
        }

        if (preset.svg) {
            return preset.svg;
        }

        if (preset.glyph) {
            return `<span class="lo-icon-glyph">${preset.glyph}</span>`;
        }

        return "";
    },

    getAvailablePresets(type = "hotspot") {
        const isPortal = type === "portal";
        const keys = Object.keys(this.presets);
        return keys.filter(k => {
            const p = this.presets[k];
            if (p.type === "all") return true;
            if (isPortal) {
                return p.type === "portal";
            }
            return p.type === "hotspot";
        });
    }
